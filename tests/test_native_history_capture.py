def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False, allow_nan=False).encode("utf-8")


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def _tree_bytes(directory):
    """Fixture-only complete file roster; no real machine paths are supplied."""
    result = {}
    for root, directories, files in os.walk(directory, followlinks=False):
        for name in sorted(directories + files):
            path = Path(root) / name
            info = path.lstat()
            relative = path.relative_to(directory).as_posix()
            if stat.S_ISDIR(info.st_mode):
                result[relative] = {"kind": "directory"}
            elif stat.S_ISREG(info.st_mode):
                result[relative] = {
                    "kind": "file", "mode": stat.S_IMODE(info.st_mode),
                    "raw_base64": base64.b64encode(path.read_bytes()).decode("ascii"),
                }
            else:
                raise AssertionError("unexpected fixture alias or special file: " + relative)
    return result


