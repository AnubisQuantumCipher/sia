"""Source-only native-history capture, never benchmark QA.

The owner runs this suite sequentially in its isolated signed-ledger fixture.
The only subprocess permitted by its positive fixture is the registered
private signed-ledger keeper; gbrain/model/scoring/publishing are prohibited.

Proposed public API: siabench.capture_native_history(*, corpus,
chain_registry, chain_names). It returns the existing admitted capture schema,
with a separately named source-only generator and complete resolver cache.
No source-history completeness, idle-gist eligibility, or cognitive win follows
from this capture. Missing provenance is not the same as no QA relevance.

Legacy characterization is SEPARATE from the future-API RED tests:
  root_characterize_legacy_bytes() -> exact canonical packet bytes
  root_compare_legacy_bytes(expected=..., expected_sha256=...) -> None
Root must retain the FIRST packet and its independently observed wire digest
BEFORE production extraction. The compare function never updates a golden.
Both legacy default and opt-in bundles and every exported byte are retained.
No post-extraction-default versus post-extraction-opt-in comparison substitutes
for that pre-extraction authority.

The fixed fixture signs literal rows with its existing deterministic test key.
Current source projects those rows without clock input; verifier basename and
launch provenance redact temporary paths, and exports have no observed wall
timestamp. Verifier bytes, rendering/projector behavior, declared constants,
and relevant fixture source must therefore remain fixed across comparison.
Root should retain source/interpreter provenance separately; implementation
source itself is expected to change and is not removed from an output payload.
If a new varying field appears, refuse the comparison and fix the fixture or
explain the semantic change; never strip, normalize, or relearn that field.
"""

