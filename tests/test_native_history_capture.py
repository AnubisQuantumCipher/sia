def root_characterize_legacy_bytes():
    """Root-run only: produce an unfiltered pre-extraction byte oracle.

    Returns bytes, does not choose a persistent output path or update a golden.
    Root must retain and independently wire-pin this result before extraction.
    This invokes ONLY the existing APIs, so it can run before the new API exists.
    The temporary dataset outputs are required observations of legacy export
    behavior, not allowed side effects of the proposed capture-only API.
    """
    case = NativeHistoryCapture(methodName="runTest")
    try:
        # setUp does not require the missing API. It gives the same signed
        # fixture an actual private owner/lifecycle root for this old API run.
        case.setUp()
        fixture = case.fixture
        with case.lib.corpus_owner():
            products = {}
            for name, captured in (("default", False), ("opt-in", True)):
                bundle = (fixture._enabled_bundle() if captured else fixture._legacy_bundle())
                output = fixture.root / ("legacy-characterization-" + name)
                fixture.bench.write_dataset(bundle, str(output), corpus=fixture.corpus)
                artifacts = fixture._published_artifacts(output, captured=captured)
                products[name] = {
                    "bundle_canonical_base64": base64.b64encode(canonical(bundle)).decode("ascii"),
                    "files": {leaf: {
                        "mode": stat.S_IMODE(path.lstat().st_mode),
                        "raw_base64": base64.b64encode(path.read_bytes()).decode("ascii"),
                    } for leaf, path in sorted(artifacts.items())},
                }
            return canonical({
                "schema": "sia-native-capture-legacy-characterization-v1",
                "fixture_sources": {
                    "ledger": _tree_bytes(Path(fixture.state)),
                    "corpus": _tree_bytes(Path(fixture.corpus)),
                    "registered_verifier_base64": base64.b64encode(
                        Path(fixture.registry["aegis"][1]).read_bytes()).decode("ascii"),
                },
                "products": products,
            })
    finally:
        case.doCleanups()


def root_compare_legacy_bytes(*, expected, expected_sha256):
    """Root supplies original whole bytes and independently retained wire pin."""
    if type(expected) is not bytes or type(expected_sha256) is not str \
            or sha(expected) != expected_sha256:
        raise AssertionError("legacy characterization authority differs")
    observed = root_characterize_legacy_bytes()
    if observed != expected:
        raise AssertionError(
            "legacy bytes changed: inspect the complete original and new packets; "
            "do not regenerate the golden or filter mismatching fields")


